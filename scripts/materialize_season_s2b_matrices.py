def update_ledger(activity_rows: list[dict], humor_rows: list[dict]) -> None:
    ledger = json.loads(LEDGER_PATH.read_text(encoding="utf-8"))
    activity_map = {episode_id: [] for episode_id in EPISODES}
    humor_map = {episode_id: [] for episode_id in EPISODES}
    for row in activity_rows:
        activity_map[row["episode_id"]].append(row["activity_id"])
    for row in humor_rows:
        humor_map[row["episode_id"]].append(row["humor_id"])
    for episode in ledger["episodes"]:
        episode["activity_ids"] = activity_map[episode["episode_id"]]
        episode["humor_ids"] = humor_map[episode["episode_id"]]
    LEDGER_PATH.write_text(json.dumps(ledger, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


